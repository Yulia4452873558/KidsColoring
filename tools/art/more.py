def horn(p, x, y, ang=-110, L=150, w=26):
    a = math.radians(ang)
    tx, ty = x + L * math.cos(a), y + L * math.sin(a)
    nx, ny = -math.sin(a) * w, math.cos(a) * w
    p.poly([(x + nx, y + ny), (tx, ty), (x - nx, y - ny)])
    for k in (0.3, 0.55, 0.78):
        cx, cy = x + (tx - x) * k, y + (ty - y) * k
        ww = w * (1 - k) * 1.05
        p.line(f"M{f(cx + nx / w * ww)} {f(cy + ny / w * ww)} L{f(cx - nx / w * ww + (tx - x) * 0.08)} {f(cy - ny / w * ww + (ty - y) * 0.08)}", sw=7)


def curl(p, cx, cy, r, rot=0):
    """Локон: капля со спиралькой."""
    with p.group(f"rotate({rot} {cx} {cy})"):
        p.shape(f"M{cx} {cy - r} C{cx + r * 1.1} {cy - r} {cx + r * 1.1} {cy + r * 0.9} {cx} {cy + r} "
                f"C{cx - r * 0.9} {cy + r} {cx - r * 1.3} {cy + r * 0.2} {cx - r * 1.6} {cy - r * 0.9} "
                f"C{cx - r * 1.1} {cy - r * 0.6} {cx - r * 0.6} {cy - r} {cx} {cy - r} Z")
        p.line(f"M{cx - r * 0.1} {cy + r * 0.35} C{cx + r * 0.5} {cy + r * 0.35} {cx + r * 0.5} {cy - r * 0.45} "
               f"{cx} {cy - r * 0.45} C{cx - r * 0.3} {cy - r * 0.45} {cx - r * 0.35} {cy - r * 0.05} {cx - r * 0.1} {cy}", sw=7)


