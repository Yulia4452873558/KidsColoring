def waves(p, y, amp=22, n=6, sw=SW):
    w = 1024 / n
    d = f"M-10 {y}"
    for i in range(n):
        d += f" Q{f(i * w + w / 4)} {f(y - amp)} {f(i * w + w / 2)} {f(y)} Q{f(i * w + 3 * w / 4)} {f(y + amp)} {f((i + 1) * w)} {f(y)}"
    p.line(d, sw)


